namespace ThesisEngine.Core;

/// <summary>
/// 南开大学研究生学位论文格式知识的权威来源。所有格式回答都从这里给出，
/// 以便把“标题 / 章节 / 摘要”等硬约束在代码中锁定，而不是只写在提示词里被用户绕开。
/// 每个条目都包含对齐（居中 / 左对齐 / 两端对齐）等硬性约束。
/// </summary>
public static class FormatKnowledge
{
    private static readonly (string[] Keywords, string Answer)[] Entries =
    {
        (new[] { "一级标题", "主标题", "论文标题", "大标题", "题目" },
         "论文主标题使用黑体三号（16 磅），居中对齐，段前段后间距均为 0 磅，单倍行距。这是不可更改的硬约束：必须居中、必须黑体三号。"),

        (new[] { "一、", "二级标题", "章标题", "章节标题", "一级标题编号" },
         "章节标题（形如“一、”）使用黑体小四号（12 磅），左对齐、首行不缩进，段前段后间距均为 0 行，固定行距 20 磅。这是硬约束：必须黑体小四、固定 20 磅行距。"),

        (new[] { "摘要", "关键词" },
         "摘要与关键词部分可使用免费的论文检测系统（知网、维普、万方）自查，不需要额外花钱。摘要正文用宋体小四，关键词另起一行、左对齐，多个关键词之间以分号分隔。"),

        (new[] { "正文", "宋体", "小四" },
         "正文中文用宋体小四（12 磅），西文用 Times New Roman 小四，两端对齐，首行缩进 2 个字符，1.5 倍行距。"),

        (new[] { "行距", "行间距", "行高" },
         "正文行距为 1.5 倍行距；章节标题使用固定值 20 磅行距。行距是硬约束，不可自行改为单倍或多倍；对齐仍按要求：标题居中、章节左对齐、正文两端对齐。"),

        (new[] { "图表", "图片", "表格", "图题", "表题", "三线表" },
         "图片应居中，宽度不超过正文版心宽度的 80%；表格使用三线表，表题置于表格上方并居中，图题置于图片下方并居中。图、表均居中对齐。"),

        (new[] { "参考文献", "引用", "引文", "脚注", "标注", "文献", "著录", "GB/T 7714" },
         "参考文献著录必须符合 GB/T 7714：作者. 题名[文献类型标识]. 出版地: 出版者, 出版年. 正文用上标[1]标注序号，并与文末列表一一对应。")
    };

    /// <summary>若问题命中格式知识库则返回权威回答；否则返回 null（视为越界）。</summary>
    public static string? TryAnswer(string question)
    {
        var q = (question ?? string.Empty).Trim();
        foreach (var entry in Entries)
        {
            foreach (var keyword in entry.Keywords)
            {
                if (q.Contains(keyword, StringComparison.OrdinalIgnoreCase))
                    return entry.Answer;
            }
        }

        return null;
    }
}
